import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

// Builds src/data/city-index.json, the offline observer search for visible-pass
// predictions (roadmap B.3), from Natural Earth's 1:10m populated places
// (public domain, ~7,300 cities and towns). Searching locally means the
// observer's location never leaves the device.
//
//   node scripts/build-city-index.mjs              download the pinned release
//   node scripts/build-city-index.mjs --from DIR   use a local copy of the file
//
// Each city is [name, region, country, lat × 100, lon × 100, population]; the
// decoder is src/core/geo/CitySearch.ts.

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const target = path.join(root, 'src/data/city-index.json')

// v5.1.2, the same pinned commit as scripts/build-place-index.mjs.
const NATURAL_EARTH_COMMIT = 'f1890d9f152c896d250a77557a5751a93d494776'
const SOURCE = 'ne_10m_populated_places_simple.geojson'

export const SCALE = 100 // units per degree (0.01° ≈ 1.1 km — ample for pass times)

async function loadSource(fromDir) {
  if (fromDir) return JSON.parse(await readFile(path.join(fromDir, SOURCE), 'utf8'))
  const url = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${NATURAL_EARTH_COMMIT}/geojson/${SOURCE}`
  const response = await fetch(url, { signal: AbortSignal.timeout(60_000) })
  if (!response.ok) throw new Error(`${SOURCE}: HTTP ${response.status}`)
  return response.json()
}

export function buildCityIndex(source) {
  const cities = source.features
    .map(({ properties: p }) => [
      p.name,
      p.adm1name && p.adm1name !== p.name ? p.adm1name : null,
      p.adm0name,
      Math.round(p.latitude * SCALE),
      Math.round(p.longitude * SCALE),
      Math.max(0, Math.round(p.pop_max ?? 0)),
    ])
    .filter(([name, , country]) => typeof name === 'string' && name.length > 0 && typeof country === 'string')
    // Most populous first: search ranks ties by population, so the client can
    // keep the first match per rank.
    .sort((a, b) => b[5] - a[5] || a[0].localeCompare(b[0]))
  return {
    _comment: `Generated by scripts/build-city-index.mjs from Natural Earth ${NATURAL_EARTH_COMMIT.slice(0, 7)} (v5.1.2, public domain). Do not hand-edit.`,
    scale: SCALE,
    cities,
  }
}

async function main() {
  const fromIndex = process.argv.indexOf('--from')
  const fromDir = fromIndex === -1 ? null : process.argv[fromIndex + 1]
  const index = buildCityIndex(await loadSource(fromDir))
  // One city per line keeps diffs readable.
  const body = index.cities.map((city) => `    ${JSON.stringify(city)}`).join(',\n')
  const json = `{\n  "_comment": ${JSON.stringify(index._comment)},\n  "scale": ${index.scale},\n  "cities": [\n${body}\n  ]\n}\n`
  await writeFile(target, json)
  console.log(`city-index.json: ${index.cities.length} places, ${(json.length / 1024).toFixed(0)} KiB`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error)
    process.exit(1)
  })
}
